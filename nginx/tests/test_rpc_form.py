"""hive.rpc_form, in a rewriter built on the nginx image, in front of PostgREST.

The fixture API (fixture/rewriter_fixture.sql) declares `f(name)` at /accounts/{name},
`p(limit)` at /limits and `v()` at /version; `g(name)` is in no spec. Each function
answers three rows (col 1, 2, 3) with the argument it got and the method PostgREST
was called with. A path the rewrite rules do not name, like /f, goes to /rpc/f.

The operator-prefixed cases fail when the module is bypassed (PostgREST reads the
value as a filter); the PostgREST-parameter cases fail when every parameter is moved
to the body (PostgREST reads a column filter there as an unknown argument).
"""
import json
from typing import Any, Dict, List, Sequence

import pytest
from rest_client import Service

_PREFIXES = ("not.", "eq.", "gt.", "in.", "like.", "is.", "fts.")
_COLS = (1, 2, 3)


def _rows(name: str, cols: Sequence[int] = _COLS, method: str = "POST") -> List[Dict[str, Any]]:
    return [{"name": name, "col": col, "method": method} for col in cols]


def test_argument_map_lists_exactly_the_declared_parameters(rpc_arguments: str) -> None:
    assert rpc_arguments == (
        "-- Generated by process_openapi.py: the parameters each /rpc/ function declares.\n"
        "return {\n"
        '    ["f"] = { ["name"] = true },\n'
        '    ["p"] = { ["limit"] = true },\n'
        '    ["v"] = {},\n'
        "}\n"
    )


@pytest.mark.parametrize("prefix", _PREFIXES)
@pytest.mark.parametrize("target", ["/f?name={value}", "/accounts/{value}"])
def test_operator_prefixed_argument_reaches_the_function(rewriter: Service, target: str, prefix: str) -> None:
    value = prefix + "blocktrades"
    answer = rewriter.get(target.format(value=value))
    assert (answer.status, answer.body) == (200, _rows(value)), answer


def test_declared_argument_named_like_a_postgrest_parameter_is_an_argument(rewriter: Service) -> None:
    answer = rewriter.get("/limits?limit=not.blocktrades")
    assert (answer.status, answer.body) == (200, _rows("not.blocktrades")), answer


@pytest.mark.parametrize(("target", "body"), [
    ("/f?name=x&col=eq.2", _rows("x", [2])),
    ("/accounts/x?col=eq.2", _rows("x", [2])),
    ("/f?name=not.x&col=eq.2", _rows("not.x", [2])),
    ("/f?name=x&col=gte.2&col=lte.2", _rows("x", [2])),
    ("/f?name=x&select=col", [{"col": col} for col in _COLS]),
    ("/f?name=x&order=col.desc", _rows("x", [3, 2, 1])),
    ("/f?name=x&limit=1&offset=1", _rows("x", [2])),
    ("/f?name=x&or=(col.eq.1,col.eq.3)", _rows("x", [1, 3])),
    ("/f?name=x&not.and=(col.gte.2,col.lte.2)", _rows("x", [1, 3])),
    ("/limits?limit=x&col=eq.3", _rows("x", [3])),
])
def test_other_parameters_keep_their_postgrest_meaning(rewriter: Service, target: str, body: List[Any]) -> None:
    answer = rewriter.get(target)
    assert (answer.status, answer.body) == (200, body), answer


@pytest.mark.parametrize(("target", "value"), [
    ("/f?name=a%26b%20c+d", "a&b c d"),
    ("/f?name=1%2B1%3D2", "1+1=2"),
    ("/f?na%6De=not.x", "not.x"),
    ("/accounts/a%26b%3Dc", "a&b=c"),
    ("/accounts/not.a%20b", "not.a b"),
])
def test_percent_encoded_argument_arrives_decoded_once(rewriter: Service, target: str, value: str) -> None:
    answer = rewriter.get(target)
    assert (answer.status, answer.body) == (200, _rows(value)), answer


def test_repeated_argument_arrives_in_order(rewriter: Service, postgrest: Service) -> None:
    # PostgREST takes the last of a repeated form field, so the answer names the last value.
    answer = rewriter.get("/f?name=not.a&name=not.b")
    assert (answer.status, answer.body) == (200, _rows("not.b")), answer
    assert answer == postgrest.post_form("/rpc/f", "name=not.a&name=not.b")


@pytest.mark.parametrize(("target", "upstream"), [
    ("/g?name=x", "/rpc/g?name=x"),
    ("/g?name=x&col=eq.2", "/rpc/g?name=x&col=eq.2"),
    ("/g?name=eq.x", "/rpc/g?name=eq.x"),
    ("/f?col=eq.2", "/rpc/f?col=eq.2"),
    ("/version", "/rpc/v"),
])
def test_call_without_declared_argument_is_forwarded_unchanged(rewriter: Service, postgrest: Service, target: str,
                                                               upstream: str) -> None:
    answer = rewriter.get(target)
    assert answer == postgrest.get(upstream), answer


def test_function_absent_from_the_map_stays_a_get(rewriter: Service) -> None:
    answer = rewriter.get("/g?name=x&col=eq.2")
    assert (answer.status, answer.body) == (200, _rows("x", [2], method="GET")), answer
    assert rewriter.get("/g?name=eq.x").body["code"] == "PGRST202"


_COMPARED_HEADERS = ("content-type", "content-range")


@pytest.mark.parametrize(("target", "status"), [
    ("/accounts/not.blocktrades", 200),
    ("/f?name=eq.x&col=eq.2", 200),
    ("/f?name=x&col=eq.notanumber", 400),
    ("/g?name=eq.x", 404),
])
def test_head_answers_as_get_without_body(rewriter: Service, target: str, status: int) -> None:
    head, get = rewriter.in_turn(("HEAD", target), ("GET", target))
    assert head.status == get.status == status, (head, get)
    assert head.body == b""
    assert get.body != b""
    assert {h: head.headers.get(h) for h in _COMPARED_HEADERS} == {h: get.headers.get(h) for h in _COMPARED_HEADERS}


@pytest.mark.parametrize("target", ["/accounts/not.blocktrades", "/f?name=eq.x&col=eq.2"])
def test_head_leaves_the_connection_to_the_next_answer(rewriter: Service, target: str) -> None:
    # A body sent after a HEAD's headers would stay on the connection and be read as the
    # start of the next answer, which then fails to parse.
    head, get, head_again, get_again = rewriter.in_turn(("HEAD", target), ("GET", target),
                                                        ("HEAD", target), ("GET", target))
    assert (head.status, head.body, head_again.body) == (200, b"", b"")
    assert get.status == get_again.status == 200
    assert json.loads(get.body) == json.loads(get_again.body) == rewriter.get(target).body
